const makeUser = async () => {
  const email = `${crypto.randomUUID()}@test.local`;
  const row = (await sql('insert into users(email,password_hash,name) values($1,$2,$3) returning id', [email, 'x', 'Test Owner'])).rows[0];
  return { ...row, cookie: `applika_session=${await signSessionToken(row.id, email)}` };
};
