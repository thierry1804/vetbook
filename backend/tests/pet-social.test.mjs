  console.log('OK medal privacy, ownership, rotation and revocation');

  const marker = crypto.randomUUID().slice(0, 8);
  await sql(`insert into pets(user_id,local_id,name,species,discoverable) select $1,1000+n,$2||' '||n,'Canine',true from generate_series(1,105) n`, [owner.id, marker]);
  const search = `/directory?species=Canine&q=${marker}&offset=`;
  const directory = await call(search + '100', visitor);
  assert.equal(directory.status, 200);
  assert.equal(directory.json.pets.length, 5);
  assert.equal(directory.json.next, null);
  const prior = await call(search + '80', visitor);
  assert.ok(!directory.json.pets.some((p) => prior.json.pets.some((before) => before.id === p.id)));
